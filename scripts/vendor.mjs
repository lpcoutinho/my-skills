#!/usr/bin/env node
// Vendors third-party skills into skills/<name>, the way akitaonrails/my-skills
// vendors humanizer: a plain copy with .git (and the inert .github) stripped.
//
// vendor.sources (hand-edited) says what to take from each upstream repo;
// vendor.lock (generated) records which commit each skill came from.
//
//   node scripts/vendor.mjs update [repo|skill...]   pull upstream, rewrite skills/ and vendor.lock
//   node scripts/vendor.mjs outdated                 compare vendor.lock with upstream (no writes)
//   node scripts/vendor.mjs list                     show sources and vendored skills
//
// Options for update: --force overwrites skills with uncommitted local changes.
// Review the result with `git diff skills/` before committing: upstream text
// goes live in every agent as soon as it lands here.

import { execFileSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { fileURLToPath } from "node:url";

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const SKILLS_DIR = path.join(REPO, "skills");
const SOURCES_FILE = path.join(REPO, "vendor.sources");
const LOCK_FILE = path.join(REPO, "vendor.lock");
const LOCK_HEADER = "# generated by scripts/vendor.mjs; edit vendor.sources instead\n# name\trepo\tref\tsubpath\tcommit\tvendored_at";
const STRIP = [".git", ".github"];
const TEXT_EXT = new Set([".md", ".yaml", ".yml", ".json", ".txt"]);

const git = (args, opts = {}) =>
  execFileSync("git", args, { encoding: "utf8", stdio: ["ignore", "pipe", "pipe"], ...opts }).trim();

// Each line: <owner/repo> <ref> <selector>... where a selector is
//   path/to/skill          one skill folder (or "." for a repo-root skill)
//   @path/to/plugin.json   every skill listed in that manifest's "skills" field
//   exclude:a,b            drop these skills (upstream names)
//   rename:a=b,c=d         install upstream skill a as b, and rewrite references to it
function readSources() {
  const sources = [];
  for (const [i, raw] of fs.readFileSync(SOURCES_FILE, "utf8").split("\n").entries()) {
    const line = raw.replace(/#.*/, "").trim();
    if (!line) continue;
    const [repo, ref, ...rest] = line.split(/\s+/);
    if (!repo?.includes("/") || !ref || rest.length === 0) {
      throw new Error(`vendor.sources:${i + 1}: expected "<owner/repo> <ref> <selector>..."`);
    }
    const src = { repo, ref, paths: [], manifests: [], exclude: new Set(), rename: new Map() };
    for (const token of rest) {
      if (token.startsWith("exclude:")) token.slice(8).split(",").forEach((n) => src.exclude.add(n));
      else if (token.startsWith("rename:")) {
        for (const pair of token.slice(7).split(",")) {
          const [from, to] = pair.split("=");
          if (!from || !to) throw new Error(`vendor.sources:${i + 1}: bad rename "${pair}"`);
          src.rename.set(from, to);
        }
      } else if (token.startsWith("@")) src.manifests.push(token.slice(1));
      else src.paths.push(token);
    }
    sources.push(src);
  }
  return sources;
}

function readLock() {
  if (!fs.existsSync(LOCK_FILE)) return [];
  return fs
    .readFileSync(LOCK_FILE, "utf8")
    .split("\n")
    .filter((l) => l && !l.startsWith("#"))
    .map((l) => {
      const [name, repo, ref, subpath, commit, vendoredAt] = l.split("\t");
      return { name, repo, ref, subpath, commit, vendoredAt };
    });
}

function writeLock(entries) {
  const rows = [...entries]
    .sort((a, b) => a.name.localeCompare(b.name))
    .map((e) => [e.name, e.repo, e.ref, e.subpath, e.commit, e.vendoredAt].join("\t"));
  fs.writeFileSync(LOCK_FILE, [LOCK_HEADER, ...rows].join("\n") + "\n");
}

function skillPathsIn(checkout, src) {
  const found = [...src.paths];
  for (const manifest of src.manifests) {
    const json = JSON.parse(fs.readFileSync(path.join(checkout, manifest), "utf8"));
    const base = path.dirname(path.join(checkout, manifest));
    // Claude plugin.json resolves "skills" against the plugin root (the repo
    // root for a manifest under .claude-plugin/).
    const root = path.basename(base) === ".claude-plugin" ? path.dirname(base) : base;
    const list = Array.isArray(json.skills) ? json.skills : json.skills ? [json.skills] : [];
    for (const entry of list) {
      const abs = path.resolve(root, entry);
      if (fs.existsSync(path.join(abs, "SKILL.md"))) found.push(path.relative(checkout, abs) || ".");
      else {
        // A directory of skills rather than one skill.
        for (const child of fs.readdirSync(abs)) {
          if (fs.existsSync(path.join(abs, child, "SKILL.md"))) found.push(path.relative(checkout, path.join(abs, child)));
        }
      }
    }
  }
  return found.map((p) => {
    const upstreamName = p === "." ? src.repo.split("/")[1] : path.basename(p);
    return { subpath: p, upstreamName, name: src.rename.get(upstreamName) ?? upstreamName };
  }).filter((s) => !src.exclude.has(s.upstreamName));
}

function isDirty(name) {
  try {
    return git(["status", "--porcelain", "--", `skills/${name}`], { cwd: REPO }) !== "";
  } catch {
    return false; // not a git checkout
  }
}

function walkFiles(dir) {
  return fs.readdirSync(dir, { withFileTypes: true }).flatMap((d) => {
    const p = path.join(dir, d.name);
    return d.isDirectory() ? walkFiles(p) : [p];
  });
}

// Rewrites references to renamed skills ("code-review", `/code-review`,
// "call the Skill tool with code-review") in every text file of the source,
// so cross-skill calls keep working under the new name.
function applyRenames(dirs, rename) {
  if (rename.size === 0) return;
  const rules = [...rename].map(([from, to]) => [
    new RegExp(`(?<![\\w.-])${from.replace(/[-]/g, "\\-")}(?![\\w-])`, "g"),
    to,
  ]);
  for (const dir of dirs) {
    for (const file of walkFiles(dir)) {
      if (!TEXT_EXT.has(path.extname(file))) continue;
      const before = fs.readFileSync(file, "utf8");
      const after = rules.reduce((text, [re, to]) => text.replace(re, to), before);
      if (after !== before) fs.writeFileSync(file, after);
    }
  }
}

function update(filters, force) {
  const lockAtStart = readLock();
  const sources = readSources().filter(
    (s) => filters.length === 0 || filters.includes(s.repo) || lockAtStart.some((e) => filters.includes(e.name) && e.repo === s.repo),
  );
  if (sources.length === 0) throw new Error(`no source matches: ${filters.join(" ")}`);

  let lock = lockAtStart;
  const today = new Date().toISOString().slice(0, 10);
  const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "my-skills-vendor-"));
  const changed = [];

  try {
    for (const src of sources) {
      const checkout = path.join(tmp, src.repo.replace("/", "__"));
      git(["clone", "--quiet", "--depth", "1", "--branch", src.ref, `https://github.com/${src.repo}.git`, checkout]);
      const commit = git(["rev-parse", "HEAD"], { cwd: checkout });
      const skills = skillPathsIn(checkout, src);

      // Refuse to clobber a skill owned by someone else: a local skill or
      // another source's vendored skill with the same name.
      for (const s of skills) {
        const owner = lock.find((e) => e.name === s.name);
        if (owner && owner.repo !== src.repo) throw new Error(`${s.name}: already vendored from ${owner.repo}`);
        if (!owner && fs.existsSync(path.join(SKILLS_DIR, s.name))) {
          throw new Error(`${s.name}: skills/${s.name} is a local skill; add a rename: for this source`);
        }
        if (!fs.existsSync(path.join(checkout, s.subpath, "SKILL.md"))) {
          throw new Error(`${src.repo}: no SKILL.md at ${s.subpath}`);
        }
      }

      const previous = lock.filter((e) => e.repo === src.repo);
      const gone = previous.filter((e) => !skills.some((s) => s.name === e.name));
      const blocked = [...skills.map((s) => s.name), ...gone.map((e) => e.name)].filter(
        (n) => fs.existsSync(path.join(SKILLS_DIR, n)) && isDirty(n),
      );
      if (blocked.length && !force) {
        throw new Error(`uncommitted changes in skills/{${blocked.join(",")}}; commit or stash them, or pass --force`);
      }

      const written = [];
      for (const s of skills) {
        const dest = path.join(SKILLS_DIR, s.name);
        fs.rmSync(dest, { recursive: true, force: true });
        fs.cpSync(path.join(checkout, s.subpath), dest, {
          recursive: true,
          filter: (p) => !STRIP.includes(path.basename(p)),
        });
        written.push(dest);
      }
      applyRenames(written, src.rename);

      for (const e of gone) {
        fs.rmSync(path.join(SKILLS_DIR, e.name), { recursive: true, force: true });
        changed.push(`removed  ${e.name} (no longer in ${src.repo})`);
      }

      lock = lock.filter((e) => e.repo !== src.repo);
      for (const s of skills) {
        const old = previous.find((e) => e.name === s.name);
        const same = old?.commit === commit;
        lock.push({ name: s.name, repo: src.repo, ref: src.ref, subpath: s.subpath, commit, vendoredAt: same ? old.vendoredAt : today });
        if (!old) changed.push(`added    ${s.name}`);
        else if (!same) changed.push(`updated  ${s.name} ${old.commit.slice(0, 7)}..${commit.slice(0, 7)}`);
      }
      // Save after each source so a later failure leaves skills/ and the lock in step.
      writeLock(lock);
      console.log(`${src.repo}@${src.ref} ${commit.slice(0, 12)}: ${skills.length} skill(s)`);
    }
  } finally {
    fs.rmSync(tmp, { recursive: true, force: true });
  }

  console.log(changed.length ? changed.join("\n") : "everything already at upstream HEAD");
}

function outdated() {
  const lock = readLock();
  let behind = 0;
  for (const src of readSources()) {
    const entries = lock.filter((e) => e.repo === src.repo);
    // A bare "main" pattern also matches refs like changeset-release/main, so
    // ask for the exact branch, then the exact tag.
    const refs = git(["ls-remote", `https://github.com/${src.repo}.git`, `refs/heads/${src.ref}`, `refs/tags/${src.ref}`])
      .split("\n")
      .map((l) => l.split("\t"));
    const remote = (refs.find(([, r]) => r === `refs/heads/${src.ref}`) ?? refs.find(([, r]) => r === `refs/tags/${src.ref}`))?.[0];
    if (!remote) throw new Error(`${src.repo}: ref ${src.ref} not found upstream`);
    const commits = new Set(entries.map((e) => e.commit));
    const current = commits.size === 1 ? [...commits][0] : null;
    if (current === remote) console.log(`ok        ${src.repo}@${src.ref} ${remote.slice(0, 12)}`);
    else {
      behind++;
      const from = current ? current.slice(0, 12) : entries.length ? "mixed" : "not vendored";
      console.log(`outdated  ${src.repo}@${src.ref} ${from} -> ${remote.slice(0, 12)}  https://github.com/${src.repo}/compare/${current ?? src.ref}...${remote}`);
    }
  }
  if (behind) console.log(`\n${behind} source(s) behind. Run: make update`);
}

function list() {
  const lock = readLock();
  for (const src of readSources()) {
    const entries = lock.filter((e) => e.repo === src.repo);
    console.log(`${src.repo}@${src.ref} (${entries.length})`);
    for (const e of entries) console.log(`  ${e.name.padEnd(32)} ${e.commit.slice(0, 7)}  ${e.vendoredAt}`);
  }
}

const [cmd, ...args] = process.argv.slice(2);
const force = args.includes("--force");
const rest = args.filter((a) => a !== "--force");
try {
  if (cmd === "update") update(rest, force);
  else if (cmd === "outdated") outdated();
  else if (cmd === "list") list();
  else {
    console.log(fs.readFileSync(fileURLToPath(import.meta.url), "utf8").split("\n").slice(1, 14).map((l) => l.replace(/^\/\/ ?/, "")).join("\n"));
    process.exit(cmd ? 2 : 0);
  }
} catch (err) {
  console.error(`error: ${err.message}`);
  process.exit(1);
}
